'use strict';
// Builds js/xlmeta.js from xLights' own effect metadata
// (xLights/resources/effectmetadata/*.json): for every effect, its settings with
// the exact key xLights stores them under, their defaults, ranges and choices.
// node tools/xlmeta.js [path to the xLights source]   (default C:/dev/xLights)
const fs = require('fs'), path = require('path');
const src = path.join(process.argv[2] || 'C:/dev/xLights', 'resources/effectmetadata');
const KIND = { int: 'i', float: 'f', bool: 'b', enum: 'e', string: 's', file: 's', font: 's' };

// JsonEffectPanel::GetEffectString: the setting key's middle part
function prefixOf(p) {
    if (p.settingPrefix) return p.settingPrefix;
    switch (p.controlType) {
        case 'slider': return (p.divisor || 1) > 1 ? 'TEXTCTRL' : 'SLIDER';
        case 'checkbox': return 'CHECKBOX';
        case 'choice': case 'combobox': return 'CHOICE';
        case 'spin': return 'SPINCTRL';
        case 'text': return 'TEXTCTRL';
        case 'filepicker': return 'FILEPICKERCTRL';
        case 'fontpicker': return 'FONTPICKER';
    }
    return null;
}
const firstSentence = s => { if (!s) return ''; const m = /^(.*?[.!?])(\s|$)/.exec(s); return (m ? m[1] : s).slice(0, 220); };

const out = {};
for (const f of fs.readdirSync(src).sort()) {
    if (!f.endsWith('.json') || f.startsWith('_')) continue;
    const j = JSON.parse(fs.readFileSync(path.join(src, f), 'utf8'));
    const props = [];
    for (const p of j.properties || []) {
        if (p.platform === 'ipad') continue;
        const pre = prefixOf(p);
        if (!pre) continue;
        const kind = KIND[p.type] || 's';
        const div = p.divisor || 1;
        const row = { id: p.id, key: `E_${pre}_${p.id}`, k: kind, d: p.default ?? (kind === 'b' ? false : kind === 'e' ? (p.options || [''])[0] : kind === 's' ? '' : 0), l: p.label || p.id };
        if (p.min != null) row.min = p.min / (pre === 'SLIDER' ? 1 : 1);
        if (p.max != null) row.max = p.max;
        if (div > 1) row.div = div;
        if (div > 1 && pre === 'SLIDER') row.raw = 1;
        if (p.options) row.o = p.options;
        if (p.dynamicOptions) row.dyn = p.dynamicOptions;
        if (p.valueCurve) row.vc = 1;
        const t = firstSentence(p.description || p.tooltip);
        if (t) row.t = t;
        // float sliders keep min/max in slider units (value * divisor)
        if (div > 1) { if (row.min != null) row.min /= div; if (row.max != null) row.max /= div; }
        props.push(row);
    }
    out[j.effectName] = props;
}
const body = `'use strict';
// Generated by tools/xlmeta.js from xLights' resources/effectmetadata. Do not edit.
// For each xLights effect: its settings, the key xLights stores each under (key),
// kind (i int, f float, b bool, e choice, s text), default (d), range, choices (o),
// float divisor (div; raw: the key holds value * div) and a short description (t).
const XLMeta = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'xlmeta.js'), body);
console.log('wrote js/xlmeta.js:', Object.keys(out).length, 'effects,', (body.length / 1024).toFixed(0), 'KB');
